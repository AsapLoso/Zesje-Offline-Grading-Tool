#!/usr/bin/env python3
"""
Populate Empty Template from Grader Exports (XLSX/JSON/JSONL) or Vision Consensus Payload.

Reads the empty template generated by generate_empty_sheet.py and populates it with
grades from various input formats:
  - Grader HTML export (XLSX/JSON) - from the offline grader's export buttons
  - Vision consensus payload (JSON) - e.g., q8_zesje_staged_payload.json
  - Rubric JSONL - one line per student with criteria scores

Matches students by Student ID (column A in template).
Outputs populated sheet to data/<exam>/populated/populated_grades.xlsx
"""

import sys
import json
import argparse
from pathlib import Path
from typing import Dict, List, Any, Optional, Union

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

from openpyxl import load_workbook, Workbook
from openpyxl.styles import Alignment, Font
from openpyxl.utils import get_column_letter


SCRIPT_DIR = Path(__file__).parent.resolve()
from exam_config import add_exam_argument, load_exam_config_from_args


def find_empty_template(config: Dict[str, Any]) -> Optional[Path]:
    """Locate the empty template generated by generate_empty_sheet.py."""
    template_dir = Path(config["exam_dir"]) / "templates"
    template_path = template_dir / "empty_template.xlsx"

    if template_path.exists():
        return template_path
    return None


def parse_template_structure(template_path: Path) -> Dict[str, Any]:
    """Parse the empty template to understand column structure."""
    wb = load_workbook(template_path, data_only=True)
    ws = wb.active

    headers = {}
    for col in range(1, ws.max_column + 1):
        cell = ws.cell(row=3, column=col)
        if cell.value:
            headers[col] = str(cell.value).strip()

    # Find key columns
    student_id_col = None
    set_aside_col = None
    grading_status_col = None
    criteria_columns = []
    remarks_col = None

    for col, header in headers.items():
        header_lower = header.lower()
        if "student id" in header_lower:
            student_id_col = col
        elif "set aside" in header_lower:
            set_aside_col = col
        elif "grading status" in header_lower:
            grading_status_col = col
        elif "remark" in header_lower:
            remarks_col = col
        else:
            criteria_columns.append(col)

    return {
        "max_column": ws.max_column,
        "max_row": ws.max_row,
        "headers": headers,
        "student_id_col": student_id_col,
        "set_aside_col": set_aside_col,
        "grading_status_col": grading_status_col,
        "criteria_columns": criteria_columns,
        "remarks_col": remarks_col,
    }


def load_grader_xlsx(input_path: Path) -> List[Dict[str, Any]]:
    """Load grades from Grader HTML XLSX export."""
    wb = load_workbook(input_path, data_only=True)
    ws = wb.active

    # First row is headers
    headers = [str(cell.value).strip() if cell.value else "" for cell in ws[1]]

    # Map headers to column indices
    student_id_idx = None
    set_aside_idx = None
    grading_status_idx = None
    remarks_idx = None
    criteria_indices = []

    for i, h in enumerate(headers):
        h_lower = h.lower()
        if "student id" in h_lower:
            student_id_idx = i
        elif "set aside" in h_lower:
            set_aside_idx = i
        elif "grading status" in h_lower:
            grading_status_idx = i
        elif "remark" in h_lower:
            remarks_idx = i
        else:
            criteria_indices.append(i)

    students = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        if not row or not row[student_id_idx]:
            continue

        student_id = str(row[student_id_idx]).strip()
        criteria = {}
        for idx, crit_idx in enumerate(criteria_indices):
            val = row[crit_idx]
            if val is not None and str(val).strip():
                criteria[str(idx + 1)] = 1 if str(val).strip() in ("1", "TRUE", "True", "true", 1) else 0

        set_aside = row[set_aside_idx] if set_aside_idx is not None else False
        if isinstance(set_aside, str):
            set_aside = set_aside.strip().upper() == "TRUE"
        elif isinstance(set_aside, (int, float)):
            set_aside = bool(set_aside)

        grading_status = row[grading_status_idx] if grading_status_idx is not None else "PENDING"
        if isinstance(grading_status, str):
            grading_status = grading_status.strip().upper()

        remarks = str(row[remarks_idx]) if remarks_idx is not None and row[remarks_idx] else ""

        students.append({
            "student_id": student_id,
            "criteria": criteria,
            "set_aside": set_aside,
            "grading_status": grading_status,
            "remarks": remarks
        })

    return students


def load_grader_json(input_path: Path) -> List[Dict[str, Any]]:
    """Load grades from Grader HTML JSON export."""
    with open(input_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    students = []
    for key, grade in data.items():
        # Key format: "problem_id/student_id.jpg" or similar
        # Extract student_id from key
        student_id = key.split("/")[-1].replace(".jpg", "").replace(".png", "")
        
        selections = grade.get("selections", [])
        # selections are already 1-indexed criteria numbers (keystrokes 1-7)
        criteria = {str(s): 1 for s in selections if str(s).isdigit()}
        
        students.append({
            "student_id": student_id,
            "criteria": criteria,
            "set_aside": grade.get("set_aside", False),
            "grading_status": grade.get("grading_status", "GRADED"),
            "remarks": grade.get("remarks", "")
        })

    return students


def load_vision_consensus(input_path: Path) -> List[Dict[str, Any]]:
    """Load grades from Vision consensus payload (q8_zesje_staged_payload.json format)."""
    with open(input_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    records = data.get("submissions") or data.get("students") or []
    
    # Option ID to keystroke mapping matching Zesje root feedback children order:
    # 26: All correct (key 1), 27: My!=Nx (key 2), 28: mu(y) (key 3), 29: Phi (key 4),
    # 30: f(y) (key 5), 31: Phi=C (key 6), 32: Blank/0pt (key 7)
    rubric_opt_to_key = {
        26: "1", 27: "2", 28: "3", 29: "4", 30: "5", 31: "6", 32: "7"
    }

    result = []
    for s in records:
        sid = str(s.get("student_number") or s.get("student_id") or "").strip()
        criteria = {}
        if "criteria" in s:
            criteria = {str(k): int(v) for k, v in s["criteria"].items()}
        elif "effective_feedback" in s:
            fb = s["effective_feedback"]
            for opt in fb:
                if isinstance(opt, int) and opt in rubric_opt_to_key:
                    criteria[rubric_opt_to_key[opt]] = 1
                elif str(opt).isdigit():
                    criteria[str(opt)] = 1

        result.append({
            "student_id": sid,
            "criteria": criteria,
            "set_aside": s.get("set_aside", False),
            "grading_status": s.get("status") or s.get("grading_status") or "GRADED",
            "remarks": s.get("remarks", "")
        })
    return result


def load_jsonl(input_path: Path) -> List[Dict[str, Any]]:
    """Load grades from Rubric JSONL (one line per student)."""
    students = []
    with open(input_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
                students.append({
                    "student_id": str(record.get("student_id", "")).strip(),
                    "criteria": {str(k): int(v) for k, v in record.get("criteria", {}).items()},
                    "set_aside": record.get("set_aside", False),
                    "grading_status": record.get("grading_status", "GRADED"),
                    "remarks": record.get("remarks", "")
                })
            except json.JSONDecodeError as e:
                print(f"[WARN] Line {line_num}: Invalid JSON - {e}")
    return students


def load_input_data(input_path: Path, fmt: Optional[str]) -> List[Dict[str, Any]]:
    """Load input data based on format auto-detection or explicit format."""
    if fmt:
        fmt = fmt.lower()
    else:
        # Auto-detect from extension
        suffix = input_path.suffix.lower()
        if suffix == ".xlsx":
            fmt = "xlsx"
        elif suffix == ".json":
            # Could be grader JSON or vision consensus - try both
            fmt = "auto_json"
        elif suffix == ".jsonl":
            fmt = "jsonl"
        else:
            raise ValueError(f"Unknown file format: {suffix}. Use --format to specify.")

    if fmt == "xlsx":
        return load_grader_xlsx(input_path)
    elif fmt == "json":
        return load_grader_json(input_path)
    elif fmt == "jsonl":
        return load_jsonl(input_path)
    elif fmt == "vision" or fmt == "consensus":
        return load_vision_consensus(input_path)
    elif fmt == "auto_json":
        # Try vision consensus first (has "students" key), then grader JSON
        with open(input_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if "students" in data:
            return load_vision_consensus(input_path)
        else:
            return load_grader_json(input_path)
    else:
        raise ValueError(f"Unsupported format: {fmt}")


def populate_template(
    template_path: Path,
    input_students: List[Dict[str, Any]],
    output_path: Path,
    template_structure: Dict[str, Any]
) -> Dict[str, Any]:
    """Populate the empty template with input grades."""
    wb = load_workbook(template_path)
    ws = wb.active

    student_id_col = template_structure["student_id_col"]
    set_aside_col = template_structure["set_aside_col"]
    grading_status_col = template_structure["grading_status_col"]
    criteria_columns = template_structure["criteria_columns"]
    remarks_col = template_structure["remarks_col"]

    # Build lookup from template: student_id -> row number
    template_students = {}
    for row in range(4, ws.max_row + 1):
        cell = ws.cell(row=row, column=student_id_col)
        if cell.value:
            template_students[str(cell.value).strip()] = row

    # Build lookup from input data
    input_lookup = {s["student_id"]: s for s in input_students if s["student_id"]}

    stats = {
        "total_input": len(input_lookup),
        "total_template": len(template_students),
        "matched": 0,
        "missing_in_template": [],
        "missing_in_input": [],
        "populated_rows": 0,
        "new_rows_added": 0
    }

    # Populate matched students
    for student_id, row_num in template_students.items():
        if student_id in input_lookup:
            data = input_lookup[student_id]
            stats["matched"] += 1

            # Set Aside
            if set_aside_col:
                cell = ws.cell(row=row_num, column=set_aside_col, value="TRUE" if data["set_aside"] else "FALSE")
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Grading Status
            if grading_status_col:
                cell = ws.cell(row=row_num, column=grading_status_col, value=data["grading_status"])
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Criteria columns
            for i, crit_col in enumerate(criteria_columns):
                criteria_key = str(i + 1)
                value = data["criteria"].get(criteria_key, 0)
                cell = ws.cell(row=row_num, column=crit_col, value=1 if value else 0)
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Remarks
            if remarks_col:
                ws.cell(row=row_num, column=remarks_col, value=data["remarks"])

            stats["populated_rows"] += 1
        else:
            stats["missing_in_input"].append(student_id)

    # Add new rows for input students not in template
    next_row = ws.max_row + 1
    for student_id in input_lookup:
        if student_id not in template_students:
            stats["missing_in_template"].append(student_id)
            data = input_lookup[student_id]

            # Student ID
            ws.cell(row=next_row, column=student_id_col, value=student_id)

            # Set Aside
            if set_aside_col:
                cell = ws.cell(row=next_row, column=set_aside_col, value="TRUE" if data["set_aside"] else "FALSE")
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Grading Status
            if grading_status_col:
                cell = ws.cell(row=next_row, column=grading_status_col, value=data["grading_status"])
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Criteria columns
            for i, crit_col in enumerate(criteria_columns):
                criteria_key = str(i + 1)
                value = data["criteria"].get(criteria_key, 0)
                cell = ws.cell(row=next_row, column=crit_col, value=1 if value else 0)
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Remarks
            if remarks_col:
                ws.cell(row=next_row, column=remarks_col, value=data["remarks"])

            stats["populated_rows"] += 1
            stats["new_rows_added"] += 1
            next_row += 1

    # Save
    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output_path)

    return stats


def print_stats(stats: Dict[str, Any]):
    """Print population statistics."""
    print("\n" + "=" * 60)
    print("POPULATION STATISTICS")
    print("=" * 60)
    print(f"  Input students:         {stats['total_input']}")
    print(f"  Template student rows:  {stats['total_template']}")
    print(f"  Successfully matched:   {stats['matched']}")
    print(f"  New rows added:         {stats.get('new_rows_added', 0)}")
    print(f"  Rows populated:         {stats['populated_rows']}")
    
    if stats["missing_in_template"]:
        print(f"\n  [WARN] {len(stats['missing_in_template'])} students in input NOT found in template (added as new rows):")
        for sid in stats["missing_in_template"][:10]:
            print(f"    - {sid}")
        if len(stats["missing_in_template"]) > 10:
            print(f"    ... and {len(stats['missing_in_template']) - 10} more")

    if stats["missing_in_input"]:
        print(f"\n  [INFO] {len(stats['missing_in_input'])} students in template NOT in input (left as defaults):")
        for sid in stats["missing_in_input"][:10]:
            print(f"    - {sid}")
        if len(stats["missing_in_input"]) > 10:
            print(f"    ... and {len(stats['missing_in_input']) - 10} more")

    print("=" * 60)


def main():
    parser = argparse.ArgumentParser(
        description="Populate Zesje empty template from grader exports or vision consensus",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Input Formats:
  xlsx       Grader HTML XLSX export (with headers: Student ID, Set Aside, Grading Status, criteria..., Remarks)
  json       Grader HTML JSON export (object with keys like "problem_id/student_id.jpg")
  jsonl      Rubric JSONL (one JSON object per line with student_id, criteria, set_aside, grading_status, remarks)
  vision     Vision consensus payload (JSON with "students" array containing criteria dict)
  auto       Auto-detect from file extension (default)

Examples:
  python populate_sheet_from_grader.py --input grades_export.xlsx
  python populate_sheet_from_grader.py --input q8_zesje_staged_payload.json --format vision
  python populate_sheet_from_grader.py --input grades.jsonl --format jsonl --output custom_path.xlsx
        """
    )
    parser.add_argument("--input", "-i", required=True, help="Input file path (XLSX, JSON, JSONL)")
    parser.add_argument("--format", "-f", choices=["xlsx", "json", "jsonl", "vision", "auto"],
                        default="auto", help="Input format (default: auto-detect)")
    parser.add_argument("--output", "-o", help="Output path (default: data/<exam>/populated/populated_grades.xlsx)")
    parser.add_argument("--template", "-t", help="Explicit template path (overrides auto-detection)")
    add_exam_argument(parser)
    parser.add_argument("--verbose", "-v", action="store_true", help="Verbose output")

    args = parser.parse_args()

    print("=" * 70)
    print("ZESJE TEMPLATE POPULATOR")
    print("=" * 70)

    # Load config
    config = load_exam_config_from_args(args)
    course_name = config.get("course_name", "unknown")
    exam_id = config.get("exam_id")
    print(f"Course: {course_name}")
    print(f"Exam ID: {exam_id}")
    print()

    # Find empty template
    template_path = Path(args.template).resolve() if args.template else find_empty_template(config)
    if not template_path:
        print("[ERROR] Empty template not found!")
        print("Run generate_empty_sheet.py first to create the template.")
        sys.exit(1)
    print(f"[OK] Template: {template_path}")

    # Parse template structure
    template_structure = parse_template_structure(template_path)
    print(f"  Student ID col:      {template_structure['student_id_col']}")
    print(f"  Set Aside col:       {template_structure['set_aside_col']}")
    print(f"  Grading Status col:  {template_structure['grading_status_col']}")
    print(f"  Criteria columns:    {template_structure['criteria_columns']}")
    print(f"  Remarks col:         {template_structure['remarks_col']}")
    print()

    # Load input data
    input_path = Path(args.input).resolve()
    if not input_path.exists():
        print(f"[ERROR] Input file not found: {input_path}")
        sys.exit(1)

    fmt = None if args.format == "auto" else args.format
    print(f"Loading input: {input_path} (format: {fmt or 'auto'})")
    input_students = load_input_data(input_path, fmt)
    print(f"[OK] Loaded {len(input_students)} student records from input")
    print()

    # Determine output path
    if args.output:
        output_path = Path(args.output).resolve()
    else:
        output_path = Path(config["exam_dir"]) / "populated" / "populated_grades.xlsx"

    # Populate template
    print("Populating template...")
    stats = populate_template(template_path, input_students, output_path, template_structure)

    print(f"\n[OK] Populated template saved to: {output_path}")
    print_stats(stats)

    print("\nNext steps:")
    print(f"  1. Review populated file: {output_path}")
    print("  2. Upload with: python 4_upload/zesje_uploader.py --dry-run")
    print("=" * 70)


if __name__ == "__main__":
    main()
